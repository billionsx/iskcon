-- ИНДЕКСЫ КАТАЛОГА КАТХИ · ЗКН-Ф027
--
-- ПОЧЕМУ. Замер 2026-09-01T05Z: 6 617 555 прочитанных строк за сутки при
-- цели 500 000 и пределе 5 000 000 — превышение самого предела в 1.3 раза.
-- Четыре запроса из верхушки принадлежат ОДНОМУ каталогу — каталогу лекций,
-- который питает плеер:
--
--   1 609 376 строк · 304 вызова · `katha_tracks WHERE speaker_slug = ?1`
--   1 050 016 строк · 152 вызова · `SELECT COUNT(*) FROM katha_tracks`
--      51 182 строк · 157 вызовов · `katha_albums WHERE speaker_slug = ?1`
--      51 182 строк · 157 вызовов · `SELECT COUNT(*) FROM katha_albums`
--   ───────────────────────────────────────────────────────────────────────
--   2 761 756 строк = 41.7 % ВСЕГО суточного чтения базы.
--
-- ПРИЧИНА. У обеих таблиц индекс только один — автоиндекс первичного ключа
-- (`id`). Отбор по `speaker_slug` подходящего индекса не находит и читает
-- таблицу ЦЕЛИКОМ: 5 294 строки ради записей одного голоса, 326 строк ради
-- альбомов одного голоса. У D1 прочитанная строка — это строка, ПРОСМОТРЕННАЯ
-- движком, а не отданная в ответ, поэтому проход и есть счёт.
--
-- ЧТО ДЕЛАЕМ. Индекс по `speaker_slug` на обеих таблицах. Порядок колонок
-- выбран под фактические запросы: оба сортируют по `sort`, поэтому вторая
-- колонка снимает ещё и сортировку.
--
-- ЧЕГО НЕ ДЕЛАЕМ. `COUNT(*)` этим не лечится: он считает ВСЮ таблицу, и
-- индекс лишь меняет, что именно проходить. Это отдельная правка в коде —
-- счётчик каталога не обязан пересчитываться на каждый запрос.
-- ══════════════════════════════════════════════════════════════════════════

CREATE INDEX IF NOT EXISTS idx_katha_tracks_speaker
  ON katha_tracks (speaker_slug, sort);

CREATE INDEX IF NOT EXISTS idx_katha_albums_speaker
  ON katha_albums (speaker_slug, sort);

-- Записи внутри цикла — тот же разбор: страница альбома отбирает по album_id.
CREATE INDEX IF NOT EXISTS idx_katha_tracks_album
  ON katha_tracks (album_id, sort);
