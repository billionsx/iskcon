def main():
    d = json.load(open(P, encoding="utf-8"))
    tabs = d.get("tabs", [])
    if any(t.get("id") == TAB["id"] for t in tabs):
        print("таб уже есть — заменяю")
        tabs = [t for t in tabs if t.get("id") != TAB["id"]]
    # порядок в prev не критичен (compose сам ставит [vklad → куратор → аппарат]),
    # но держим читаемо: после vklad.
    out, placed = [], False
    for t in tabs:
        out.append(t)
        if t.get("id") == "vklad-gauranga-lila" and not placed:
            out.append(TAB); placed = True
    if not placed:
        out.insert(0, TAB)
    d["tabs"] = out
    json.dump(d, open(P, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("prev.json: таб put-dzhivy вставлен · табов теперь", len(out))


if __name__ == "__main__":
    main()
